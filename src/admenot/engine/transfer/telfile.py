"""Droga 3: pliki do ręcznego importu w `Download/` nowego telefonu (spec Etapu 3 §4 p. 3).

SMS i MMS razem w jednym pliku SMS Backup & Restore (`<smses>` z `<sms>` i `<mms>`, załączniki
w base64), połączenia w osobnym pliku SB&R, kontakty jako vCard 3.0. Pliki zostają na telefonie
celowo — serwisant albo klient importuje je ręcznie (Kontakty → Importuj), program tylko podaje, gdzie leżą.
"""

from __future__ import annotations

import base64
import re
import tempfile
import time
import uuid
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from ..adb.transport import AdbTransport
from . import telephony as tel
from .mms import message_address
from .pusher import Pusher
from .telrecords import CallRecord, ContactRecord, MmsRecord, SmsRecord

DOWNLOAD = "/sdcard/Download"
NAMES: dict[str, str] = {
    "sms": "admenot-wiadomosci-{stamp}.xml",
    "calls": "admenot-polaczenia-{stamp}.xml",
    "contacts": "admenot-kontakty-{stamp}.vcf",
}
_STAMP = re.compile(r"[A-Za-z0-9._-]{1,40}")
_HEAD = "<?xml version='1.0' encoding='UTF-8' standalone='yes' ?>"
_COMMENT = "<!-- Generated by AdMeNot; SMS Backup & Restore (SyncTech) compatible format -->"

ManualKind = Literal["contacts", "sms", "calls"]


@dataclass(frozen=True)
class ManualStep:
    kind: ManualKind
    remote: str  # ścieżka pliku na telefonie (`/sdcard/Download/…`)


class ManualFileError(Exception):
    """Pliku nie udało się wgrać (`adb push` z kodem ≠ 0)."""


# --------------------------------------------------------------------------------------
# Treść plików
# --------------------------------------------------------------------------------------
def _sms_row(r: SmsRecord) -> dict[str, str | None]:
    return {"address": r.address, "date": str(r.date), "date_sent": str(r.date_sent), "type": str(r.type),
            "read": str(r.read), "status": str(r.status), "subject": r.subject, "body": r.body}


def _attrs(pairs: list[tuple[str, str | None]]) -> str:
    return " ".join(f'{k}="{tel.xml_attr(v)}"' for k, v in pairs)


def _mms_element(r: MmsRecord) -> list[str]:
    addrs = [{"address": a, "type": str(t)} for a, t in r.addrs]
    pairs: list[tuple[str, str | None]] = [
        ("date", str(r.date)), ("date_sent", str(r.date_sent)), ("msg_box", str(r.msg_box)),
        ("read", str(r.read)), ("seen", "1"), ("locked", "0"), ("sub_id", "-1"),
        ("m_type", "132" if r.msg_box == 1 else "128"), ("ct_t", "application/vnd.wap.multipart.related"),
        ("sub", r.subject), ("address", message_address(str(r.msg_box), addrs)),
        ("readable_date", tel.readable(str(r.date))), ("contact_name", "(Unknown)")]
    out = [f"  <mms {_attrs(pairs)}>", "    <parts>"]
    for p in r.parts:
        seq = "-1" if p.content_type.split(";")[0].strip().lower() == "application/smil" else "0"
        part = _attrs([("seq", seq), ("ct", p.content_type), ("name", p.name), ("chset", "106" if p.text else None),
                       ("text", p.text)])
        data = ""
        if p.file is not None:
            try:
                blob = p.file.read_bytes()
            except OSError:  # plik załącznika zniknął z kopii: wiadomość bez tej części, ale jest
                continue
            data = f' data="{base64.b64encode(blob).decode("ascii")}"'
        out.append(f"      <part {part}{data} />")
    out += ["    </parts>", "    <addrs>"]
    out += [f"      <addr {_attrs([('address', a), ('type', str(t)), ('charset', '106')])} />"
            for a, t in r.addrs]
    out += ["    </addrs>", "  </mms>"]
    return out


def messages_xml(sms: list[SmsRecord], mms: list[MmsRecord]) -> str:
    """SMS i MMS w jednym pliku SB&R (SB&R przywraca oba z jednego `<smses>`)."""
    sms_lines = [line for line in tel.build_sms_xml([_sms_row(r) for r in sms], {}).split("\n")
                 if line.startswith("  <sms ")]
    head = (f'<smses count="{len(sms) + len(mms)}" backup_set="{uuid.uuid4()}" '
            f'backup_date="{int(time.time() * 1000)}" type="full">')
    out = [_HEAD, _COMMENT, head, *sms_lines]
    for r in mms:
        out += _mms_element(r)
    out.append("</smses>")
    return "\n".join(out) + "\n"


def calls_xml(calls: list[CallRecord]) -> str:
    rows = [{"number": r.number, "date": str(r.date), "duration": str(r.duration), "type": str(r.type),
             "presentation": str(r.presentation), "subscription_id": None, "name": r.name} for r in calls]
    return tel.build_calls_xml(rows, {})


def contacts_vcf(contacts: list[ContactRecord]) -> str:
    """vCard 3.0 tym samym kodem co eksport kopii (`telephony.build_vcards`)."""
    rows_c, rows_d = [], []
    for i, c in enumerate(contacts):
        cid = str(i)
        rows_c.append({"_id": cid, "display_name": c.display, "starred": "1" if c.starred else "0"})
        rows_d += [{"contact_id": cid, "raw_contact_id": cid, "mimetype": d.mimetype, **dict(d.values)}
                   for d in c.rows]
    return tel.build_vcards(rows_c, [], rows_d)[0]


# --------------------------------------------------------------------------------------
# Wgranie
# --------------------------------------------------------------------------------------
def _never() -> bool:
    return False


def _noop() -> None:
    return None


def write_manual_files(adb: AdbTransport, pusher: Pusher, kinds_records: dict[str, list],
                       stamp: str) -> list[ManualStep]:
    """Wgrywa pliki do ręcznego importu dla kategorii z rekordami (`sms` i `mms` razem w pliku `sms`).
    `ManualFileError` przy nieudanym `push`; `AdbError` rozłączenia przechodzi wyżej."""
    if not _STAMP.fullmatch(stamp):
        raise ValueError(f"bad stamp {stamp!r}")
    builders: list[tuple[ManualKind, Callable[[], str]]] = []
    sms, mms = kinds_records.get("sms") or [], kinds_records.get("mms") or []
    if kinds_records.get("contacts"):
        builders.append(("contacts", lambda: contacts_vcf(kinds_records["contacts"])))
    if sms or mms:
        builders.append(("sms", lambda: messages_xml(sms, mms)))
    if kinds_records.get("calls"):
        builders.append(("calls", lambda: calls_xml(kinds_records["calls"])))
    if not builders:
        return []
    steps: list[ManualStep] = []
    with tempfile.TemporaryDirectory(prefix="admenot-manual-") as tmp:
        adb.shell(f"mkdir -p {DOWNLOAD}")
        for kind, build in builders:
            name = NAMES[kind].format(stamp=stamp)
            local = Path(tmp) / name
            local.write_text(build(), encoding="utf-8", newline="")
            remote = f"{DOWNLOAD}/{name}"
            res = pusher.push([local], remote, _never, _noop)
            if res.rc != 0:
                raise ManualFileError(f"push {name} failed")
            steps.append(ManualStep(kind, remote))
    return steps

